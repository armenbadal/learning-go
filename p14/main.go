func Fetch(ctx context.Context, delay time.Duration) (string, error) {
	if err := ctx.Err(); err != nil {
		return "", err
	}

	timer := time.NewTimer(delay)
	defer timer.Stop()

	select {
	case <-timer.C:
		if err := ctx.Err(); err != nil {
			return "", err
		}
		return "data", nil
	case <-ctx.Done():
		return "", ctx.Err()
	}
}

