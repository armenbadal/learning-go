package main

import (
	"context"
	"errors"
	"fmt"
	"io"
	"net/http"
	"sync"
)

/*
1. Run N HTTP calls concurrently, collect the results,
   and cancel the rest on the first error.

What to grade: Tests goroutines, context cancellation,
and error propagation. Watch for a WaitGroup or errgroup,
a bounded number of goroutines, and no leaked goroutine
when one call fails.
*/

func fetchURL(ctx context.Context, url string) (string, error) {
	request, err := http.NewRequestWithContext(ctx, "GET", url, nil)
	if err != nil {
		return "", err
	}

	response, err := http.DefaultClient.Do(request)
	if err != nil {
		return "", err
	}
	defer response.Body.Close()
	if response.StatusCode < http.StatusOK || response.StatusCode >= http.StatusMultipleChoices {
		return "", fmt.Errorf("GET %s: %s", url, response.Status)
	}

	body, err := io.ReadAll(response.Body)
	if err != nil {
		return "", err
	}

	return string(body), nil
}

type fetchResult struct {
	url  string
	body string
	err  error
}

func main() {
	urls := []string{
		"https://cacm.acm.org/federal-funding-of-academic-research/the-llvm-compiler-infrastructure/",
		"https://www.example.com",
		"https://www.google.com",
	}

	const maxConcurrent = 4
	workerCount := min(maxConcurrent, len(urls))

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	jobs := make(chan string, len(urls))
	results := make(chan fetchResult, len(urls))
	for _, url := range urls {
		jobs <- url
	}
	close(jobs)

	var workers sync.WaitGroup
	workers.Add(workerCount)
	for range workerCount {
		go func() {
			defer workers.Done()
			for {
				select {
				case <-ctx.Done():
					return
				case url, ok := <-jobs:
					if !ok || ctx.Err() != nil {
						return
					}

					body, err := fetchURL(ctx, url)
					if err != nil {
						cancel()
					}
					results <- fetchResult{url: url, body: body, err: err}
				}
			}
		}()
	}

	go func() {
		workers.Wait()
		close(results)
	}()

	var firstErr error
	for result := range results {
		if result.err != nil {
			if firstErr == nil || (errors.Is(firstErr, context.Canceled) && !errors.Is(result.err, context.Canceled)) {
				firstErr = result.err
			}
			continue
		}
		fmt.Printf("%s: %s\n", result.url, result.body)
	}

	if firstErr != nil {
		fmt.Println("Error:", firstErr)
	}
}

